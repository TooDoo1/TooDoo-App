// One-off generator: geocodes every city in lib/sweden-regions.ts via Open-Meteo
// and writes lib/sweden-city-coords.ts. Run: node scripts/generate-city-coords.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'lib/sweden-regions.ts'), 'utf8');

// Parse { name: '...', cities: [ '...', ... ] } blocks.
const regions = [];
const blockRe = /name:\s*'([^']+)',\s*cities:\s*\[([^\]]+)\]/g;
let match;
while ((match = blockRe.exec(source)) !== null) {
  const lan = match[1];
  const cities = [...match[2].matchAll(/'([^']+)'/g)].map((m) => m[1]);
  regions.push({ lan, cities });
}

const total = regions.reduce((n, r) => n + r.cities.length, 0);
console.log(`Found ${regions.length} län, ${total} cities`);

async function geocode(lan, city) {
  const url = `https://geocoding-api.open-meteo.com/v1/search?name=${encodeURIComponent(
    city
  )}&count=10&language=sv&format=json&countryCode=SE`;
  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(10000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const json = await res.json();
      const results = (json.results ?? []).filter((r) => r.country_code === 'SE');
      const inLan = results.find((r) => r.admin1 === lan);
      const exact = results.find(
        (r) => r.name.toLowerCase() === city.toLowerCase() && r.admin1 === lan
      );
      const best = exact ?? inLan ?? results[0];
      if (!best) return null;
      return { lat: best.latitude, lng: best.longitude, admin1: best.admin1 };
    } catch (err) {
      if (attempt === 2) {
        console.warn(`FAILED ${lan} / ${city}: ${err.message}`);
        return null;
      }
      await new Promise((r) => setTimeout(r, 1000 * (attempt + 1)));
    }
  }
  return null;
}

const entries = [];
const misses = [];
const queue = regions.flatMap((r) => r.cities.map((city) => ({ lan: r.lan, city })));
let done = 0;

async function worker() {
  while (queue.length > 0) {
    const job = queue.shift();
    if (!job) return;
    const hit = await geocode(job.lan, job.city);
    done += 1;
    if (done % 50 === 0) console.log(`${done}/${total}`);
    if (hit) {
      entries.push({ ...job, lat: hit.lat, lng: hit.lng, admin1: hit.admin1 });
    } else {
      misses.push(job);
    }
  }
}

await Promise.all(Array.from({ length: 4 }, worker));

entries.sort((a, b) =>
  `${a.lan}|${a.city}`.localeCompare(`${b.lan}|${b.city}`, 'sv')
);

const lines = entries.map(
  (e) =>
    `  '${e.lan.toLocaleLowerCase('sv-SE')}|${e.city.toLocaleLowerCase('sv-SE')}': { lat: ${e.lat}, lng: ${e.lng} },`
);

const out = `// Generated by scripts/generate-city-coords.mjs — do not edit by hand.
// Static coordinates for every city in the location picker so switching place
// never depends on a live geocoding service.

export type CityCoords = { lat: number; lng: number };

const SWEDEN_CITY_COORDS: Record<string, CityCoords> = {
${lines.join('\n')}
};

/** Lookup key is "län|city", lowercase (sv-SE). */
export function staticCoordsForCity(lan: string, city: string): CityCoords | null {
  const key = \`\${lan.trim().toLocaleLowerCase('sv-SE')}|\${city.trim().toLocaleLowerCase('sv-SE')}\`;
  return SWEDEN_CITY_COORDS[key] ?? null;
}
`;

writeFileSync(join(root, 'lib/sweden-city-coords.ts'), out);
console.log(`Wrote ${entries.length} entries; ${misses.length} misses`);
if (misses.length) console.log('Misses:', misses.map((m) => `${m.lan}/${m.city}`).join(', '));
